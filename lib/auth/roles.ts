import { SystemRole } from "@prisma/client";

// ГЛАВНЫЙ_ТЕХНИЧЕСКИЙ_ДИРЕКТОР получает ровно те же права, что и АДМИН —
// прямая просьба при введении роли (2026-08-06), без исключений (финансы,
// company-wide дашборд, задачи по всем проектам, смена ролей, безвозвратное
// удаление). Единая точка проверки, чтобы не размножать
// "systemRole === АДМИН || systemRole === ГЛАВНЫЙ_ТЕХНИЧЕСКИЙ_ДИРЕКТОР" по
// всему коду — если раньше где-то проверялось "===  АДМИН" как gate на
// полный доступ, теперь должно проверяться через этот хелпер.
export function isFullAdmin(systemRole: SystemRole): boolean {
  return systemRole === SystemRole.АДМИН || systemRole === SystemRole.ГЛАВНЫЙ_ТЕХНИЧЕСКИЙ_ДИРЕКТОР;
}

