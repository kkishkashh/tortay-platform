// выпадающих списках выбора роли, и в сайдбаре (см. app/(dashboard)/layout.tsx),
// чтобы "ГЛАВНЫЙ_ТЕХНИЧЕСКИЙ_ДИРЕКТОР" никогда не показывался пользователю
// как сырое значение enum.
