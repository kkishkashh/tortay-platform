-- Data migration
-- До этой миграции SystemRole.РУКОВОДИТЕЛЬ играл роль полного администратора
-- (см. schema.prisma). Вводим третью роль АДМИН как новый "полный доступ",
-- а РУКОВОДИТЕЛЬ становится более узкой ролью (без автоматического доступа
-- к финансам и без дашборда по всем проектам компании, см. lib/projects/
-- permissions.ts::canManageFinance и lib/departments/queries.ts::
-- getCurrentUserRoleTier). Чтобы никто не потерял сегодняшний доступ —
-- переносим ВСЕХ существующих РУКОВОДИТЕЛЬ в АДМИН; РУКОВОДИТЕЛЬ начинает
-- жизнь с нуля держателей, назначается вручную через "Кадровые данные".
UPDATE "users" SET "systemRole" = 'АДМИН' WHERE "systemRole" = 'РУКОВОДИТЕЛЬ';
